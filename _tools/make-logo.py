#!/usr/bin/env python3
"""Generates the four UIMA blocks as inline SVGs in _includes/svg/:

  uima-logo.svg       in the original colours; only the tile outlines (class "tile")
                      are coloured by CSS, per theme
  uima-logo-mono.svg  one colour, like the GitHub mark: tiles in currentColor, letters
                      knocked out in the page background colour (class "letter")


    python3 _tools/make-logo.py path/to/uima.pdf

The input is the official artwork from https://www.apache.org/logos/res/uima/uima.pdf;
Inkscape converts it to SVG. Only the blocks are kept (not the wordmark, tagline or TM),
with their original shapes.
"""
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

NS = "http://www.w3.org/2000/svg"
BLOCK_COLOURS = {"#49830d", "#e89800", "#d80028", "#253d93"}   # green, orange, red, blue
OUTLINE = "#3a3a3a"
OUT_DIR = Path(__file__).resolve().parent.parent / "_includes" / "svg"


def inkscape(*args):
    subprocess.run(["inkscape", *args], check=True, capture_output=True)


def style_of(el):
    return dict(kv.split(":", 1) for kv in el.get("style", "").split(";") if ":" in kv)


def is_block_part(el):
    s = style_of(el)
    return s.get("fill") in BLOCK_COLOURS or s.get("stroke") == OUTLINE


def coords(s, digits):
    """Shortens the numbers in path data or a transform without changing the shape."""
    def fmt(m):
        v = f"{float(m.group()):.{digits}f}".rstrip("0").rstrip(".")
        return "0" if v in ("-0", "") else v
    return re.sub(r"-?\d+(?:\.\d+)?(?:e-?\d+)?", fmt, s)


def main(pdf):
    ET.register_namespace("", NS)
    with tempfile.TemporaryDirectory() as tmp:
        full, blocks, cropped = (Path(tmp, n) for n in ("full.svg", "blocks.svg", "cropped.svg"))
        inkscape(pdf, "--export-type=svg", "--export-plain-svg", f"--export-filename={full}")

        tree = ET.parse(full)
        for g in tree.getroot().iter(f"{{{NS}}}g"):
            for el in list(g):
                if el.tag == f"{{{NS}}}path" and not is_block_part(el):
                    g.remove(el)
        tree.write(blocks)
        inkscape(str(blocks), "--export-area-drawing", "--export-plain-svg",
                 "--export-type=svg", f"--export-filename={cropped}")

        root = ET.parse(cropped).getroot()
        paths = []

        def walk(el, transforms):
            if el.get("transform"):
                transforms = transforms + [el.get("transform")]
            for child in el:
                if child.tag == f"{{{NS}}}g":
                    walk(child, transforms)
                elif child.tag == f"{{{NS}}}path":
                    t = transforms + ([child.get("transform")] if child.get("transform") else [])
                    s = style_of(child)
                    d = coords(child.get("d"), 2)
                    paths.append({
                        "fill": s.get("fill", "none"),
                        "outline": coords(s["stroke-width"], 2) if s.get("stroke") == OUTLINE else None,
                        # tiles are plain four-corner shapes; letters are long outlines
                        "tile": len(re.findall(r"[-\d.]+", d)) <= 10,
                        "transform": coords(" ".join(t), 7) if t else None,
                        "d": d,
                    })

        walk(root, [])

    viewbox = coords(root.get("viewBox"), 2)
    write("uima-logo.svg", viewbox, [colour_path(p) for p in paths])
    write("uima-logo-mono.svg", viewbox, [mono_path(p) for p in paths if p["fill"] != "none"])


def path_element(attrs, p):
    if p["transform"]:
        attrs.append(f'transform="{p["transform"]}"')
    attrs.append(f'd="{p["d"]}"')
    return "  <path " + " ".join(attrs) + "/>"


def colour_path(p):
    attrs = []
    if p["outline"]:
        attrs += ['class="tile"', f'stroke-width="{p["outline"]}"', 'stroke-linejoin="bevel"']
    attrs.append(f'fill="{p["fill"]}"')
    return path_element(attrs, p)


def mono_path(p):
    return path_element(['fill="currentColor"' if p["tile"] else 'class="letter"'], p)


def write(name, viewbox, paths):
    variant = name.removesuffix(".svg")
    svg = [f'<svg class="{variant}" viewBox="{viewbox}" width="32" height="32" '
           'aria-hidden="true" xmlns="http://www.w3.org/2000/svg">',
           "  <!-- Generated by _tools/make-logo.py from https://www.apache.org/logos/res/uima/uima.pdf -->",
           *paths,
           "</svg>"]
    out = OUT_DIR / name
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(svg) + "\n")
    print(f"{out.name}: {len(paths)} paths, {sum(map(len, svg))} bytes")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else sys.exit(__doc__))
