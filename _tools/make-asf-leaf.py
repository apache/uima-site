#!/usr/bin/env python3
"""Generates _includes/svg/asf-leaf.svg, the ASF oak leaf shown next to the ASF link.

    python3 _tools/make-asf-leaf.py path/to/feather.svg

The input is the official icon from the ASF press kit,
https://www.apache.org/foundation/press/kit/feather.svg (the oak leaf, despite the name).
The ASF brand guidelines require the official artwork to be used unchanged, so shapes and
colours are kept as they are. Only the file's <style> classes are turned into fill
attributes, so that inlining it cannot leak CSS into the page.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

NS = "http://www.w3.org/2000/svg"
OUT = Path(__file__).resolve().parent.parent / "_includes" / "svg" / "asf-leaf.svg"


def main(src):
    root = ET.parse(src).getroot()
    style = "".join(e.text or "" for e in root.iter(f"{{{NS}}}style"))
    fills = dict(re.findall(r"\.([\w-]+)\s*\{\s*fill:\s*(#[0-9a-fA-F]{3,6})\s*;?\s*\}", style))
    paths = []
    for p in root.iter(f"{{{NS}}}path"):
        fill = fills[p.get("class")]
        paths.append(f'  <path fill="{fill}" d="{p.get("d")}"/>')
    svg = [f'<svg class="asf-leaf" viewBox="{root.get("viewBox")}" width="13" height="20" '
           'aria-hidden="true" xmlns="http://www.w3.org/2000/svg">',
           "  <!-- The ASF oak leaf, generated by _tools/make-asf-leaf.py from the official",
           "       https://www.apache.org/foundation/press/kit/feather.svg. Do not alter: the",
           "       ASF brand guidelines require the official artwork, unchanged. -->",
           *paths,
           "</svg>"]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(svg) + "\n")
    print(f"{OUT.name}: {len(paths)} paths, colours {sorted(set(fills.values()))}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else sys.exit(__doc__))
